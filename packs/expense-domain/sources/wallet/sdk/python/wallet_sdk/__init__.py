"""A complete, dependency-free client for the BudgetBakers Wallet REST API.

The package covers every operation in the OpenAPI 3.1 specification (version
2.0.0), models every schema, validates every documented constraint before a
request leaves the process, and surfaces every documented failure mode as a
typed exception.

Authentication
--------------
All endpoints take a bearer token minted for the Wallet flavour of the API. A
Board token on a Wallet path yields 403 — see :class:`ForbiddenError`.

    from wallet_sdk import WalletClient, between, contains_i

    client = WalletClient(token=os.environ["WALLET_API_TOKEN"])
    page = client.list_accounts(limit=50, name=contains_i("checking"))

    for record in client.iter_records(record_date=between("2024-01-01", "2024-04-01")):
        print(record.record_date, record.amount.value, record.counter_party)

Batch endpoints
---------------
``POST /records``, and every ``PATCH`` and ``DELETE``, are batch endpoints.
They answer 200 (all succeeded), 207 (mixed), 400 (all failed with client
errors) and 500 (all failed with server errors) with the SAME envelope. This
SDK therefore returns the parsed envelope — not an exception — for all four
statuses, and the caller inspects ``summary`` and ``results``. A 400 that is a
plain validation error (malformed body, batch too large) is still raised; the
two are told apart by the shape of the body.

Errors
------
Every non-2xx that is not a batch envelope becomes an :class:`APIError`
subclass carrying the status, the server's message, the raw body and the
response metadata. Client-side validation failures never reach the network and
raise :class:`InvalidRequestError`, which lists every problem it found.
"""

